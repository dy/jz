#!/usr/bin/env node
// Regenerates src/unicode-id.generated.js: the code points above ASCII that
// ECMAScript's IdentifierName admits (§12.7: ID_Start, then ID_Continue), taken
// from the running Node's Unicode data. The parser (src/parse.js) reads the
// tables with a binary search: jz compiles its own compiler, and a regex with
// \p{…} would need property tables the compiled compiler does not carry.
//
// Two sets: START (ID_Start) and PART (ID_Continue less ID_Start: combining
// marks, digits of other scripts, connector punctuation, U+00B7, ZWNJ, ZWJ).
// A name's first character is in START; every later one is in START or PART.
// Each set is a sorted list of range boundaries [first, last + 1, …], written
// as the distance from the previous boundary. ZWNJ and ZWJ join PART by
// ECMAScript's own rule, whatever the Unicode version says.
//
// Regenerate on a Node with newer Unicode: node scripts/gen-unicode-id.mjs
import { writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'

const OUT = fileURLToPath(new URL('../src/unicode-id.generated.js', import.meta.url))
const START = /\p{ID_Start}/u, CONT = /\p{ID_Continue}/u

const bounds = (has) => {
  const out = []
  let inside = false
  for (let c = 0x80; c <= 0x110000; c++) {
    const now = c <= 0x10ffff && has(c)
    if (now !== inside) out.push(c), inside = now
  }
  return out
}
const deltas = (b) => b.map((v, i) => v - (i ? b[i - 1] : 0))
const lines = (d) => {
  const out = []
  for (let i = 0; i < d.length; i += 24) out.push('  ' + d.slice(i, i + 24).join(', ') + ',')
  return out.join('\n')
}

const ch = (c) => String.fromCodePoint(c)
const start = bounds(c => START.test(ch(c)))
const part = bounds(c => !START.test(ch(c)) && (CONT.test(ch(c)) || c === 0x200c || c === 0x200d))

writeFileSync(OUT, `// Generated by scripts/gen-unicode-id.mjs from Unicode ${process.versions.unicode} (Node ${process.version}).
// Do not edit: regenerate with \`node scripts/gen-unicode-id.mjs\`.
//
// The code points above ASCII of ECMAScript's IdentifierName: ID_START holds
// ID_Start, ID_PART holds what ID_Continue adds to it (with ZWNJ and ZWJ). Each
// is a sorted list of range boundaries [first, last + 1, …], every value the
// distance from the one before.
export const UNICODE_VERSION = '${process.versions.unicode}'

export const ID_START = [
${lines(deltas(start))}
]

export const ID_PART = [
${lines(deltas(part))}
]
`)
console.log(`wrote ${OUT}: Unicode ${process.versions.unicode}, ${start.length / 2} start ranges, ${part.length / 2} part ranges`)
