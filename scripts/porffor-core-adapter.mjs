#!/usr/bin/env node
/**
 * Build a minimal, standard-JS Porffor compiler-core source for JZ.
 *
 * This is an opt-in compatibility boundary, not a JZ language extension. It
 * asks Porffor's own selfhost bundler for its no-precompiled-builtin variant,
 * removes CLI/native-only modules, and replaces three host conveniences with
 * equivalent explicit JavaScript:
 *
 * - dynamic RegExp construction becomes host validation followed by an
 *   in-Wasm throw, so Porffor's try/catch keeps working;
 * - fixed-name metadata deletes call one computed-key helper, which uses JZ's
 *   existing dynamic-object path;
 * - descriptor-backed lazy comptime entries become eager table entries. The
 *   adapter preserves their non-enumeration contract at the two table census
 *   sites. No precompiled entries can later exercise the removed setters.
 *
 * Every source rewrite is shape- and count-checked. A Porffor source change
 * therefore rejects instead of silently producing a different compiler.
 */

import { execFileSync } from 'node:child_process'
import { createHash } from 'node:crypto'
import { existsSync, readFileSync, rmSync, writeFileSync } from 'node:fs'
import { dirname, resolve } from 'node:path'
import { fileURLToPath, pathToFileURL } from 'node:url'

export const PORFFOR_COMPAT_REV = '03b6b54fda4bdf242e085d23768a6e31490fa58d'
export const PORFFOR_COMPAT_IMPORT = 'porffor:compat'

const here = dirname(fileURLToPath(import.meta.url))
const root = resolve(here, '..')

const countOf = (source, needle) => source.split(needle).length - 1

const replaceExact = (source, before, after, label, expected = 1) => {
  const count = countOf(source, before)
  if (count !== expected)
    throw new Error(`Porffor adapter: ${label} shape drifted (expected ${expected}, found ${count})`)
  return source.split(before).join(after)
}

const moduleSlice = (bundle, from, to) => {
  const startMarker = `// ${from}\n`
  const endMarker = `// ${to}\n`
  const start = bundle.indexOf(startMarker)
  const end = bundle.indexOf(endMarker, start + startMarker.length)
  if (start < 0 || end < 0 || end <= start)
    throw new Error(`Porffor adapter: missing ordered module markers ${from} -> ${to}`)
  return bundle.slice(start, end)
}

const moduleDefault = (source, moduleName) => {
  const marker = `// ${moduleName}\n`
  const start = source.indexOf(marker)
  if (start < 0) throw new Error(`Porffor adapter: missing ${moduleName}`)
  const next = source.indexOf('\n// compiler/', start + marker.length)
  const body = source.slice(start, next < 0 ? source.length : next)
  const names = [...body.matchAll(/\bconst (__m\d+_default)\s*=/g)].map(x => x[1])
  if (names.length !== 1)
    throw new Error(`Porffor adapter: ${moduleName} default shape drifted (found ${names.length})`)
  return names[0]
}

const extractPorfforCore = bundle => {
  if (!bundle.startsWith('// generated by selfhosted/build.mjs\n'))
    throw new Error('Porffor adapter: input is not a selfhosted bundle')
  const types = moduleSlice(bundle, 'compiler/types.js', 'compiler/uwebsockets.js')
  const compiler = moduleSlice(bundle, 'compiler/parser/unicode.js', 'compiler/index.js')
  return types + compiler
}

const guardAbsentPrecompiledHypot = core => replaceExact(core,
  '  _.__Math_hypot.jsLength = 2;',
  '  if (_.__Math_hypot != null) _.__Math_hypot.jsLength = 2;',
  'absent no-precompiled Math.hypot annotation')

const wrapPorfforCore = (core, version, compatibility) => {
  const parse = moduleDefault(core, 'compiler/parse.js')
  const codegen = moduleDefault(core, 'compiler/codegen.js')
  const render = moduleDefault(core, 'compiler/render.js')
  const compatImport = compatibility
    ? `import { validateRegExp as __jzValidateRegExp } from '${PORFFOR_COMPAT_IMPORT}'\n\n`
    : ''
  const compatHelpers = compatibility ? `let __jzCompatComptimeNames = new Set()
let __jzCompatDeleteOwn = (object, key) => delete object[key]
function RegExp(pattern, flags) {
  let error = __jzValidateRegExp(pattern, flags)
  if (error !== '') throw new SyntaxError(error)
}

` : ''
  const prelude = `// generated by scripts/porffor-core-adapter.mjs
// Porffor ${PORFFOR_COMPAT_REV}; no precompiled builtins; compiler core only.
${compatImport}let Prefs, argvChanged
let process = { argv: [] }
let version = ${JSON.stringify(version)}, porfforFile = '', typedInput = false, precompile = false
let pageSize = 16384, _uniqId = 0, funcBodies
${compatHelpers}`
  const wrapper = `

export let compilePorffor = (source, asModule = false) => {
  Prefs.module = asModule
  typedInput = false
  porfforFile = ''
  pageSize = Prefs.pageSize ?? 16384
  let program = ${parse}(source)
  let generated = ${codegen}(program)
  let rendered = ${render}(generated)
  return typeof rendered === 'string' ? rendered : rendered.c
}
`
  return prelude + core + wrapper
}

const DELETE_SITES = new Set([
  'oldMd.type',
  'oldMd.types',
  'oldMd.typeAnnotation',
  'oldMd.elementType',
  'oldMd.storageType',
  'scope.overrideThis',
])

/** Apply the checked compatibility rewrites to an already-extracted core. */
export function adaptPorfforCore(core, version) {
  if (typeof version !== 'string' || version.length === 0)
    throw new Error('Porffor adapter: missing runtime version')
  if (!core.includes('// compiler/builtins_precompiled.js\nconst ') ||
      !/\/\/ compiler\/builtins_precompiled\.js\nconst __m\d+_BuiltinFuncs = \(\) => \{\};/.test(core))
    throw new Error('Porffor adapter: expected Porffor no-precompiled-builtin bundle')

  const seenDeletes = []
  core = core.replace(/\bdelete ([A-Za-z_$][\w$]*)\.([A-Za-z_$][\w$]*);/g, (_all, obj, prop) => {
    const site = `${obj}.${prop}`
    seenDeletes.push(site)
    return `__jzCompatDeleteOwn(${obj}, '${prop}');`
  })
  if (seenDeletes.length !== DELETE_SITES.size ||
      seenDeletes.some(site => !DELETE_SITES.has(site)) ||
      [...DELETE_SITES].some(site => !seenDeletes.includes(site)))
    throw new Error(`Porffor adapter: static-delete sites drifted (${seenDeletes.join(', ')})`)
  if (/\bdelete [A-Za-z_$][\w$]*\./.test(core))
    throw new Error('Porffor adapter: an unsupported static delete remains')

  core = replaceExact(core,
    '    const props = autoFuncs(x);',
    '    let props = autoFuncs(x);',
    'Object prototype descriptor binding')
  core = replaceExact(core,
    "      Object.defineProperty(props, '__proto__', { value: { value: null, configurable: true }, enumerable: true });",
    "      props = { ...props, ['__proto__']: { value: null, configurable: true } };",
    'Object prototype data descriptor')

  const accessor = `    Object.defineProperty(_, name, {
      get() {
        return v;
      },
      set(x) {
        x.comptime = comptime;
        x.returnType = returnType;
        v = x;
      }
    });`
  core = replaceExact(core, accessor,
    `    __jzCompatComptimeNames.add(name);
    _[name] = v;`,
    'comptime accessor')
  core = guardAbsentPrecompiledHypot(core)

  let keyCensuses = 0
  core = core.replace(/Object\.keys\((builtinFuncs|__m\d+_builtinFuncs)\)/g, (_all, table) => {
    keyCensuses++
    return `Object.keys(${table}).filter(x => !__jzCompatComptimeNames.has(x))`
  })
  if (keyCensuses !== 2)
    throw new Error(`Porffor adapter: non-enumerable comptime Object.keys census drifted (found ${keyCensuses})`)
  let forInCensuses = 0
  core = core.replace(/^(\s*)for \(const x in (builtinFuncs|__m\d+_builtinFuncs)\) \{$/gm, (_all, indent, table) => {
    forInCensuses++
    return `${indent}for (const x in ${table}) {\n${indent}  if (__jzCompatComptimeNames.has(x)) continue;`
  })
  if (forInCensuses !== 1)
    throw new Error(`Porffor adapter: non-enumerable comptime for-in census drifted (found ${forInCensuses})`)

  // The remaining textual defineProperty calls are inside TEMPORAL_CODE, a
  // string emitted into programs that use Temporal. The core never executes
  // or compiles that string while compiling the minimal arithmetic probe.
  const remainingDescriptors = [...core.matchAll(/Object\.defineProperty/g)].length
  if (remainingDescriptors !== 8 || countOf(core, "'_temporalBrand'") !== 8)
    throw new Error(`Porffor adapter: executable descriptor sites remain (${remainingDescriptors})`)

  return wrapPorfforCore(core, version, true)
}

/** Extract only modules needed by parse -> codegen -> C rendering. */
export function adaptPorfforBundle(bundle, version) {
  return adaptPorfforCore(extractPorfforCore(bundle), version)
}

const git = (dir, ...args) => execFileSync('git', ['-C', dir, ...args], { encoding: 'utf8' }).trim()

export function buildPorfforAdapter({ porfforDir, outFile }) {
  const dir = resolve(porfforDir)
  const head = git(dir, 'rev-parse', 'HEAD')
  if (head !== PORFFOR_COMPAT_REV)
    throw new Error(`Porffor adapter: expected ${PORFFOR_COMPAT_REV}, got ${head}`)
  const dirty = git(dir, 'status', '--porcelain', '--untracked-files=no')
  if (dirty) throw new Error('Porffor adapter: tracked Porffor checkout is dirty')

  const runtimeSource = readFileSync(resolve(dir, 'runtime/index.js'), 'utf8')
  const versionMatch = runtimeSource.match(/globalThis\.version\s*=\s*(['"])(.*?)\1/)
  if (!versionMatch) throw new Error('Porffor adapter: cannot read runtime version')

  const bundleFile = resolve(dir, 'selfhosted/bundle.js')
  const prior = existsSync(bundleFile) ? readFileSync(bundleFile) : null
  try {
    execFileSync(process.execPath, ['selfhosted/build.mjs'], {
      cwd: dir,
      env: { ...process.env, SELFHOST_NOOP_PRECOMPILED: '1' },
      stdio: ['ignore', 'pipe', 'inherit'],
    })
    const core = extractPorfforCore(readFileSync(bundleFile, 'utf8'))
    const source = adaptPorfforCore(core, versionMatch[2])
    const oracleSource = wrapPorfforCore(guardAbsentPrecompiledHypot(core), versionMatch[2], false)
    writeFileSync(resolve(outFile), source)
    return { source, oracleSource, head, version: versionMatch[2] }
  } finally {
    if (prior == null) rmSync(bundleFile, { force: true })
    else writeFileSync(bundleFile, prior)
  }
}

const sha256 = value => createHash('sha256').update(value).digest('hex')

/** Explicit, slow integration check. It is not part of npm test. */
export async function verifyPorfforAdapter({ source, oracleSource, outFile }) {
  const importLine = `import { validateRegExp as __jzValidateRegExp } from '${PORFFOR_COMPAT_IMPORT}'`
  const nodeValidator = `let __jzValidateRegExp = (pattern, flags) => {
  try { new globalThis.RegExp(pattern, flags); return '' }
  catch (error) { return error.message }
}`
  if (countOf(source, importLine) !== 1)
    throw new Error('Porffor adapter: compatibility import shape drifted')

  if (typeof oracleSource !== 'string' || oracleSource.length === 0)
    throw new Error('Porffor adapter: missing unadapted Node oracle')
  const nodeFile = resolve(`${outFile}.node.mjs`)
  const oracleFile = resolve(`${outFile}.oracle.mjs`)
  writeFileSync(nodeFile, source.replace(importLine, nodeValidator))
  writeFileSync(oracleFile, oracleSource)
  try {
    const native = await import(`${pathToFileURL(nodeFile).href}?v=${Date.now()}`)
    const oracle = await import(`${pathToFileURL(oracleFile).href}?v=${Date.now()}`)
    const { compile, instantiate } = await import('../index.js')
    let regexCalls = 0
    const validateRegExp = (pattern, flags) => {
      regexCalls++
      try { new RegExp(pattern, flags); return '' }
      catch (error) { return error.message }
    }
    const opts = { imports: { [PORFFOR_COMPAT_IMPORT]: { validateRegExp } } }
    const totalStarted = performance.now()
    let started = performance.now()
    const wasm = compile(source, opts)
    const compileMs = performance.now() - started
    started = performance.now()
    const instance = instantiate(wasm, opts)
    const instantiateMs = performance.now() - started
    const calls = { unadaptedNode: 0, adaptedNode: 0, wasm: 0 }
    const executeMs = { unadaptedNode: 0, adaptedNode: 0, wasm: 0 }
    const invoke = (tier, fn) => {
      calls[tier]++
      const callStarted = performance.now()
      try { return fn() } finally { executeMs[tier] += performance.now() - callStarted }
    }
    const verifyStarted = performance.now()
    const cases = [
      ['E', '', false],
      ['A', 'let x = 40 + 2; x', false],
      ['B', 'let x = 6 * 8; x', false],
      ['R', 'var x = 1; var x = 2; x', false],
      ['G', 'let value = /a+/', false],
      ['M', 'export default 1', true],
    ]
    const rows = []
    for (const [name, input, asModule] of cases) {
      const expected = invoke('unadaptedNode', () => oracle.compilePorffor(input, asModule))
      const nativeActual = invoke('adaptedNode', () => native.compilePorffor(input, asModule))
      const actual = invoke('wasm', () => instance.exports.compilePorffor(input, asModule))
      if (nativeActual !== expected)
        throw new Error(`Porffor adapter: ${name} changed the unadapted Node C output`)
      if (actual !== expected)
        throw new Error(`Porffor adapter: ${name} C output differs between Node and JZ`)
      rows.push({ name, bytes: actual.length, sha256: sha256(actual) })
      if (name === 'A' && invoke('wasm', () => instance.exports.compilePorffor(input, false)) !== actual)
        throw new Error('Porffor adapter: immediate A -> A reuse changed output')
    }
    const again = invoke('wasm', () => instance.exports.compilePorffor(cases[1][1], false))
    if (sha256(again) !== rows[1].sha256)
      throw new Error('Porffor adapter: A after other inputs changed output')
    if (rows[1].sha256 === rows[2].sha256)
      throw new Error('Porffor adapter: A -> B did not change output')

    const invalid = 'let value = /a{2,1}/'
    let oracleError, nodeError, jzError
    try { invoke('unadaptedNode', () => oracle.compilePorffor(invalid, false)) } catch (error) { oracleError = error }
    try { invoke('adaptedNode', () => native.compilePorffor(invalid, false)) } catch (error) { nodeError = error }
    try { invoke('wasm', () => instance.exports.compilePorffor(invalid, false)) } catch (error) { jzError = error }
    if (oracleError?.name !== 'SyntaxError' || nodeError?.name !== 'SyntaxError' ||
        jzError?.name !== 'SyntaxError' || regexCalls === 0)
      throw new Error(`Porffor adapter: dynamic RegExp rejection failed (oracle=${oracleError?.name}, Node=${nodeError?.name}, JZ=${jzError?.name}, calls=${regexCalls})`)
    const recovered = invoke('wasm', () => instance.exports.compilePorffor(cases[1][1], false))
    if (sha256(recovered) !== rows[1].sha256)
      throw new Error('Porffor adapter: valid A did not recover after invalid RegExp input')
    const expectedCalls = { unadaptedNode: 7, adaptedNode: 7, wasm: 10 }
    for (const [tier, count] of Object.entries(expectedCalls))
      if (calls[tier] !== count)
        throw new Error(`Porffor adapter: ${tier} verifier call count ${calls[tier]} != ${count}`)
    const verifyMs = performance.now() - verifyStarted

    return {
      timingsMs: {
        compile: compileMs,
        instantiate: instantiateMs,
        verify: verifyMs,
        total: performance.now() - totalStarted,
        execute: executeMs,
      },
      calls,
      adapterBytes: source.length,
      regexCalls,
      rows,
    }
  } finally {
    rmSync(nodeFile, { force: true })
    rmSync(oracleFile, { force: true })
  }
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const arg = name => process.argv.find(x => x.startsWith(`--${name}=`))?.slice(name.length + 3)
  const porfforDir = arg('porffor') ?? process.env.PORFFOR_DIR ?? resolve(root, '../porffor')
  const outFile = arg('out') ?? '/tmp/jz-porffor-core.js'
  const built = buildPorfforAdapter({ porfforDir, outFile })
  console.log(`wrote ${resolve(outFile)} (${built.source.length} bytes, Porffor ${built.head.slice(0, 8)})`)
  if (process.argv.includes('--verify'))
    console.log(JSON.stringify(await verifyPorfforAdapter({ source: built.source, oracleSource: built.oracleSource, outFile }), null, 2))
}
